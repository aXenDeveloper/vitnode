/**
 * Writes `src/og-image/server/inter-fonts.gen.ts`: the four Inter WOFF files
 * the Open Graph image generator falls back to, as base64. Embedded rather
 * than read from `node_modules` at runtime, because a server bundler (Nitro,
 * tsdown, esbuild) does not copy font files a module only resolves by path.
 *
 * Run after upgrading `@fontsource/inter`:
 * `pnpm --filter @vitnode/core exec tsx scripts/generate-og-fonts.ts`
 */
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const { version } = require("@fontsource/inter/package.json") as {
  version: string;
};

const files = {
  interLatin400: "inter-latin-400-normal.woff",
  interLatin700: "inter-latin-700-normal.woff",
  interLatinExt400: "inter-latin-ext-400-normal.woff",
  interLatinExt700: "inter-latin-ext-700-normal.woff",
} as const;

const exports = Object.entries(files).map(([name, file]) => {
  const base64 = readFileSync(
    require.resolve(`@fontsource/inter/files/${file}`),
  ).toString("base64");

  return `export const ${name} = "${base64}";`;
});

writeFileSync(
  new URL("../src/og-image/server/inter-fonts.gen.ts", import.meta.url),
  [
    "// Generated by scripts/generate-og-fonts.ts - do not edit.",
    `// Inter from @fontsource/inter ${version}, WOFF, base64. Copyright 2016 The`,
    "// Inter Project Authors (https://github.com/rsms/inter), SIL Open Font",
    "// License 1.1. Server-only: imported lazily by the OG image generator.",
    "",
    ...exports,
    "",
  ].join("\n"),
);
