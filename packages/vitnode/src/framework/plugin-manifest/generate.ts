import type {
  PluginAuthor,
  PluginManifest,
} from "../../lib/plugin-manifest.js";

import { PLUGIN_MANIFEST_ERROR_PREFIX as ERROR_PREFIX } from "../../lib/plugin-manifest.js";

/** Where `vitnode build` and `vitnode dev` write a plugin's manifest, relative to its root. */
export const PLUGIN_MANIFEST_PATH = "src/manifest.gen.ts";

/** The plugin's own title and icon, written by hand - see `PluginInfo`. */
export const PLUGIN_INFO_PATH = "src/plugin-info.ts";

/** What the generated module reads from `package.json`. */
export type PluginPackageManifest = Pick<
  PluginManifest,
  "author" | "description" | "id" | "license" | "version"
>;

const isRecord = (value: unknown): value is Record<string, unknown> =>
  typeof value === "object" && value !== null && !Array.isArray(value);

const optionalText = (
  value: unknown,
  field: string,
  source: string,
): null | string => {
  if (value === undefined || value === null) return null;
  if (typeof value !== "string") {
    throw new Error(
      `${ERROR_PREFIX} \`${field}\` in ${source} has to be a string.`,
    );
  }

  const trimmed = value.trim();

  return trimmed === "" ? null : trimmed;
};

const AUTHOR_STRING = /^([^<(]*?)\s*(?:<([^>]*)>)?\s*(?:\(([^)]*)\))?$/;

const blankToNull = (value: string | undefined): null | string => {
  const trimmed = value?.trim() ?? "";

  return trimmed === "" ? null : trimmed;
};

const authorFrom = (value: unknown, source: string): null | PluginAuthor => {
  if (value === undefined || value === null) return null;

  if (typeof value === "string") {
    const match = AUTHOR_STRING.exec(value.trim());
    const name = blankToNull(match?.[1]);

    return name === null
      ? null
      : {
          email: blankToNull(match?.[2]),
          name,
          url: blankToNull(match?.[3]),
        };
  }

  if (!isRecord(value)) {
    throw new Error(
      `${ERROR_PREFIX} \`author\` in ${source} has to be a string or an object with \`name\`, \`email\` and \`url\`.`,
    );
  }

  const name = optionalText(value.name, "author.name", source);
  if (name === null) {
    throw new Error(`${ERROR_PREFIX} \`author\` in ${source} has no \`name\`.`);
  }

  return {
    email: optionalText(value.email, "author.email", source),
    name,
    url: optionalText(value.url, "author.url", source),
  };
};

/**
 * Reads the catalog's fields out of a parsed `package.json`: `name` - required,
 * it is the plugin id - and the optional `author`, `description`, `license` and `version`, `null`
 * when the package does not declare them.
 */
export const pluginManifestFromPackageJson = (
  manifest: unknown,
  source: string,
): PluginPackageManifest => {
  if (!isRecord(manifest)) {
    throw new Error(`${ERROR_PREFIX} ${source} is not a JSON object.`);
  }

  const id = optionalText(manifest.name, "name", source);
  if (id === null) {
    throw new Error(
      `${ERROR_PREFIX} ${source} has no \`name\`. A plugin's id is its package name, so it needs one.`,
    );
  }

  return {
    author: authorFrom(manifest.author, source),
    description: optionalText(manifest.description, "description", source),
    id,
    license: optionalText(manifest.license, "license", source),
    version: optionalText(manifest.version, "version", source),
  };
};

const literal = (value: null | string): string =>
  value === null ? "null" : JSON.stringify(value);

const authorLiteral = (author: null | PluginAuthor): string =>
  author === null
    ? "null"
    : `{
    name: ${literal(author.name)},
    email: ${literal(author.email)},
    url: ${literal(author.url)},
  }`;

/**
 * `src/manifest.gen.ts` - what the AdminCP plugin catalog lists.
 *
 * The package's own fields as literals, plus the title and icon of the
 * plugin's `src/plugin-info.ts` when it has one. Plain data, imported by
 * both registrations - `buildPlugin({ manifest })` and
 * `buildApiPlugin({ manifest })` - so neither copies the plugin id or a
 * version by hand.
 */
export const generatePluginManifestSource = (
  fields: PluginPackageManifest,
  { hasInfo }: { hasInfo: boolean },
): string => `/* oxlint-disable */

// This file is generated by VitNode. Do not edit it, and do not format it.
//
// It is rewritten by \`vitnode build\` and \`vitnode dev\` from this package's
// package.json - \`name\`, \`version\`, \`description\`, \`author\` and \`license\` - and the title and
// icon in \`src/plugin-info.ts\`. Pass \`manifest\` to \`buildPlugin\`,
// \`buildApiPlugin\` and \`bindApiPlugin\` - it is where the plugin id lives.
${hasInfo ? `\nimport { pluginInfo } from "./plugin-info"\n` : ""}
export const manifest = {
  id: ${literal(fields.id)},
  title: ${hasInfo ? `pluginInfo.title ?? ${literal(fields.id)}` : literal(fields.id)},
  icon: ${hasInfo ? "pluginInfo.icon ?? null" : "null"},
  description: ${literal(fields.description)},
  author: ${authorLiteral(fields.author)},
  license: ${literal(fields.license)},
  version: ${literal(fields.version)},
} as const
`;
