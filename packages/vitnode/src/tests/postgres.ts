import { drizzle } from "drizzle-orm/postgres-js";
import { randomUUID } from "node:crypto";
import { readdirSync, readFileSync } from "node:fs";
import { resolve } from "node:path";
import postgres from "postgres";

import { coreRelations } from "@/database/relations";

/** Set to a PostgreSQL URL to run the `*.postgres.test.ts` files; they skip otherwise. */
export const POSTGRES_TEST_URL = process.env.VITNODE_TEST_POSTGRES_URL;

const MIGRATIONS = resolve(
  import.meta.dirname,
  "../../../../apps/api/migrations",
);

const connectionOptions = (raw: string) => {
  const url = new URL(raw.replace(/@\//, "@localhost/"));
  const param = (name: string) => url.searchParams.get(name);

  return {
    database: decodeURIComponent(url.pathname.slice(1)),
    host: param("host") ?? decodeURIComponent(url.hostname),
    password: url.password ? decodeURIComponent(url.password) : undefined,
    port: Number(param("port") ?? (url.port || 5432)),
    user: decodeURIComponent(url.username) || "postgres",
  };
};

const statementsOf = (sqlText: string, schema: string): string[] =>
  sqlText
    .replaceAll('"public".', `"${schema}".`)
    .split("--> statement-breakpoint")
    .map(statement => statement.trim())
    .filter(Boolean);

const createTestDrizzle = (client: postgres.Sql) =>
  drizzle({ client, relations: coreRelations });

export type PostgresTestDb = ReturnType<typeof createTestDrizzle>;

export interface PostgresTestSchema {
  client: postgres.Sql;
  db: PostgresTestDb;
  drop: () => Promise<void>;
  name: string;
}

/**
 * A throwaway schema with the app's whole migration chain applied, plus the
 * given Drizzle tables (test fixtures) generated by Drizzle Kit.
 */
export const createPostgresTestSchema = async ({
  prefix,
  tables = {},
}: {
  prefix: string;
  tables?: Record<string, unknown>;
}): Promise<PostgresTestSchema> => {
  if (!POSTGRES_TEST_URL) throw new Error("VITNODE_TEST_POSTGRES_URL is unset");
  const name = `${prefix}_${randomUUID().replaceAll("-", "")}`;
  const options = connectionOptions(POSTGRES_TEST_URL);

  const admin = postgres({ ...options, max: 1, onnotice: () => undefined });
  await admin.unsafe(`create schema "${name}"`);
  await admin.end();

  const client = postgres({
    ...options,
    connection: { search_path: name },
    max: 8,
    onnotice: () => undefined,
  });

  // The search index maps `pl` to the hunspell `polish` configuration VitNode's
  // dev image installs. A stock Postgres lacks it, so the schema gets a plain
  // stand-in - nothing here searches Polish text. Only a visible one counts:
  // another test file's schema may hold its own stand-in at the same time.
  const [polish] = await client.unsafe(
    "select 1 from pg_ts_config where cfgname = 'polish' and pg_ts_config_is_visible(oid)",
  );
  if (!polish) {
    await client.unsafe(
      `create text search configuration "${name}".polish (copy = pg_catalog.simple)`,
    );
  }

  const migrations = readdirSync(MIGRATIONS).sort();
  for (const migration of migrations) {
    const text = readFileSync(
      resolve(MIGRATIONS, migration, "migration.sql"),
      "utf8",
    );
    for (const statement of statementsOf(text, name)) {
      await client.unsafe(statement);
    }
  }

  if (Object.keys(tables).length > 0) {
    const { generateDrizzleJson, generateMigration } =
      await import("drizzle-kit/api-postgres");
    const statements = await generateMigration(
      await generateDrizzleJson({}),
      await generateDrizzleJson(tables),
    );
    for (const statement of statements) {
      for (const part of statementsOf(statement, name)) {
        await client.unsafe(part);
      }
    }
  }

  return {
    client,
    db: createTestDrizzle(client),
    drop: async () => {
      await client.unsafe(`drop schema if exists "${name}" cascade`);
      await client.end();
    },
    name,
  };
};
